// Execute the captured production loader in a sandbox: no downloads or real iframes.
// Unlike an invented API mock, this reproduces its required global config/auto-mount.
import assert from "node:assert/strict"
import { readFile } from "node:fs/promises"
import test from "node:test"
import { runInNewContext } from "node:vm"
import { installRemark42 } from "../dist/runtime.js"

const loaderSource = await readFile(new URL("../fixtures/remark42-v1.18.0-embed.mjs", import.meta.url), "utf8")

/** Minimal connected DOM tree for the operations used by our code and the live loader. */
class FakeElement extends EventTarget {
	constructor(tag, connected = false) {
		super()
		this.tagName = tag.toUpperCase()
		this.rootConnected = connected
		this.attributes = new Map()
		this.dataset = {}
		this.style = {}
		this.childNodes = []
		this.parentNode = null
		this.hidden = false
		this.removed = false
		this.text = ""
		this.messages = []
		if (tag === "iframe") {
			this.contentWindow = { postMessage: (message) => this.messages.push(message) }
		}
	}

	/** Connectivity must follow parent removal, including a hidden bootstrap target. */
	get isConnected() {
		return this.parentNode ? this.parentNode.isConnected : this.rootConnected
	}

	/** The loader selects the root by document ID, not by a config.node reference. */
	get id() {
		return this.attributes.get("id") ?? ""
	}

	/** Match the browser's id property and setAttribute views. */
	set id(value) {
		this.attributes.set("id", value)
	}

	/** Keep readable status messages without executing any markup. */
	get textContent() {
		return this.text
	}

	/** Replacing status content disconnects children as real textContent assignment does. */
	set textContent(value) {
		for (const child of [...this.childNodes]) child.remove()
		this.text = String(value)
	}

	/** Record public iframe attributes generated by the actual loader. */
	setAttribute(name, value) {
		this.attributes.set(name, String(value))
	}

	/** Let tests inspect the exact thread/site/theme sent to the fake iframe. */
	getAttribute(name) {
		return this.attributes.get(name) ?? null
	}

	/** Appending an existing child moves it instead of duplicating it. */
	appendChild(child) {
		child.parentNode?.removeChild(child)
		child.parentNode = this
		child.removed = false
		this.childNodes.push(child)
		return child
	}

	/** Detach just this child and preserve its recorded state for assertions. */
	removeChild(child) {
		const index = this.childNodes.indexOf(child)
		if (index !== -1) this.childNodes.splice(index, 1)
		child.parentNode = null
		child.removed = true
		return child
	}

	/** Exercise the real loader's iframe removal on destroy. */
	remove() {
		this.parentNode?.removeChild(this)
		this.removed = true
	}

	/** The captured loader reuses an existing direct child bearing this marker. */
	querySelector(selector) {
		assert.equal(selector, ":scope > iframe[data-remark42-iframe]")
		return (
			this.childNodes.find(
				(child) => child.tagName === "IFRAME" && child.attributes.has("data-remark42-iframe"),
			) ?? null
		)
	}
}

/** A small document whose created script/iframe elements never cause network activity. */
class FakeDocument extends EventTarget {
	scripts = []
	iframes = []
	theme = "light"
	title = "Test page"
	readyState = "complete"
	documentElement = { getAttribute: () => this.theme }
	head = new FakeElement("head", true)
	body = new FakeElement("body", true)

	/** Track allocations so accidental double initialization is visible to tests. */
	createElement(tag) {
		assert.ok(["script", "div", "iframe"].includes(tag))
		const element = new FakeElement(tag)
		if (tag === "script") this.scripts.push(element)
		if (tag === "iframe") this.iframes.push(element)
		return element
	}

	/** Search the connected tree, including temporary bootstrap roots. */
	getElementById(id) {
		function find(node) {
			if (node.id === id) return node
			for (const child of node.childNodes) {
				const match = find(child)
				if (match) return match
			}
			return null
		}
		return find(this.body) ?? find(this.head)
	}

	/** Title observation belongs to Remark42 itself and is outside this lifecycle test. */
	querySelector(selector) {
		assert.equal(selector, "title")
		return null
	}
}

/** Deterministic timers keep reveal/bootstrap timeouts from slowing the test suite. */
class FakeWindow extends EventTarget {
	location = {
		protocol: "https:",
		origin: "https://taras.life",
		pathname: "/test-page",
		hash: "",
	}
	timers = new Map()
	nextTimer = 0

	/** Store callbacks so tests explicitly choose when a slow download times out. */
	setTimeout(callback, delay) {
		const id = ++this.nextTimer
		this.timers.set(id, { callback, delay })
		return id
	}

	/** Match the numeric browser timer API used by both integration and fixture. */
	clearTimeout(id) {
		this.timers.delete(id)
	}
}

/** Reproduce the component's public data attributes without building a website. */
function container(id) {
	const node = new FakeElement("div")
	node.id = "remark42"
	node.textContent = "Loading comments…"
	node.dataset = {
		remark42Host: "https://comments.taras.life",
		remark42SiteId: "taras-life",
		remark42Url: `https://taras.life/comments/${id}`,
		remark42Title: `Note ${id}`,
	}
	return node
}

/** Match Quartz's synchronous prenav, body replacement, and nav ordering. */
function navigate(doc, node) {
	doc.dispatchEvent(new Event("prenav"))
	for (const child of [...doc.body.childNodes]) child.remove()
	if (node) doc.body.appendChild(node)
	doc.dispatchEvent(new Event("nav"))
}

/** Evaluate exactly the downloaded loader; fake elements cannot fetch or execute URLs. */
function evaluateLoader(browser, doc) {
	runInNewContext(
		loaderSource,
		{
			window: browser,
			document: doc,
			URL,
			URLSearchParams,
			Event,
			console,
		},
		{ filename: "remark42-v1.18.0-embed.mjs" },
	)
}

/** Read the actual serialized iframe configuration rather than a made-up API call record. */
function iframeConfig(iframe) {
	return new URL(iframe.getAttribute("src")).searchParams
}

test("pages without a container never download Remark42 or create a bootstrap target", (t) => {
	const browser = new FakeWindow()
	const doc = new FakeDocument()
	t.after(installRemark42(browser, doc))
	doc.dispatchEvent(new Event("nav"))
	assert.equal(doc.scripts.length, 0)
	assert.equal(doc.getElementById("remark42"), null)
	assert.equal(browser.remark_config, undefined)
})

test("config exists before evaluation and the automatic first instance is adopted exactly once", (t) => {
	const browser = new FakeWindow()
	const doc = new FakeDocument()
	const node = container("a")
	doc.body.appendChild(node)
	t.after(installRemark42(browser, doc))
	doc.dispatchEvent(new Event("nav"))
	assert.equal(browser.remark_config.host, "https://comments.taras.life")
	assert.equal(browser.remark_config.site_id, "taras-life")
	assert.equal(browser.remark_config.url, "https://taras.life/comments/a")
	assert.ok(!("node" in browser.remark_config))
	const script = doc.scripts[0]
	assert.equal(script.src, "https://comments.taras.life/web/embed.mjs")
	assert.equal(script.type, "module")
	assert.equal(script.async, true)
	assert.equal(script.dataset.persist, "")

	evaluateLoader(browser, doc)
	const api = browser.REMARK42
	const create = t.mock.method(api, "createInstance")
	script.dispatchEvent(new Event("load"))
	assert.equal(create.mock.callCount(), 0)
	assert.equal(doc.iframes.length, 1)
	assert.equal(doc.iframes[0].parentNode, node)
	assert.equal(iframeConfig(doc.iframes[0]).get("url"), "https://taras.life/comments/a")
	assert.equal(iframeConfig(doc.iframes[0]).get("page_title"), "Note a")
})

test("navigation while downloading updates the automatic mount to the new thread", (t) => {
	const browser = new FakeWindow()
	const doc = new FakeDocument()
	t.after(installRemark42(browser, doc))
	const oldNode = container("old")
	navigate(doc, oldNode)
	const newNode = container("new")
	navigate(doc, newNode)
	assert.equal(doc.scripts.length, 1)
	assert.equal(browser.remark_config.url, "https://taras.life/comments/new")
	evaluateLoader(browser, doc)
	assert.equal(doc.iframes.length, 1)
	assert.equal(doc.iframes[0].parentNode, newNode)
	assert.equal(oldNode.childNodes.length, 0)
	assert.equal(iframeConfig(doc.iframes[0]).get("url"), "https://taras.life/comments/new")
})

test("leaving during download parks and discards the automatic instance, then later mounts normally", (t) => {
	const browser = new FakeWindow()
	const doc = new FakeDocument()
	t.after(installRemark42(browser, doc))
	navigate(doc, container("a"))
	navigate(doc, null)
	const parking = doc.getElementById("remark42")
	assert.ok(parking)
	assert.equal(parking.hidden, true)
	assert.equal(parking.getAttribute("aria-hidden"), "true")
	evaluateLoader(browser, doc)
	assert.equal(doc.getElementById("remark42"), null)
	assert.equal(parking.isConnected, false)
	assert.equal(doc.iframes[0].isConnected, false)
	const next = container("next")
	navigate(doc, next)
	assert.equal(doc.scripts.length, 1)
	assert.equal(doc.iframes.length, 2)
	assert.equal(doc.iframes[1].parentNode, next)
	assert.equal(iframeConfig(doc.iframes[1]).get("url"), "https://taras.life/comments/next")
})

test("later navigation destroys the previous iframe and updates config before createInstance", (t) => {
	const browser = new FakeWindow()
	const doc = new FakeDocument()
	t.after(installRemark42(browser, doc))
	navigate(doc, container("a"))
	evaluateLoader(browser, doc)
	const first = doc.iframes[0]
	navigate(doc, container("b"))
	assert.equal(first.isConnected, false)
	assert.equal(doc.iframes.length, 2)
	const second = doc.iframes[1]
	assert.equal(browser.remark_config.url, "https://taras.life/comments/b")
	assert.equal(iframeConfig(second).get("url"), "https://taras.life/comments/b")
	navigate(doc, null)
	assert.equal(second.isConnected, false)
	assert.equal(doc.getElementById("remark42"), null)
	assert.equal(doc.scripts.length, 1)
})

test("theme changes update pending configuration and the mounted widget", (t) => {
	const browser = new FakeWindow()
	const doc = new FakeDocument()
	t.after(installRemark42(browser, doc))
	navigate(doc, container("a"))
	doc.theme = "dark"
	doc.dispatchEvent(new Event("themechange"))
	evaluateLoader(browser, doc)
	const iframe = doc.iframes[0]
	assert.equal(iframeConfig(iframe).get("theme"), "dark")
	doc.theme = "light"
	doc.dispatchEvent(new Event("themechange"))
	assert.equal(browser.remark_config.theme, "light")
	assert.equal(iframe.style.colorScheme, "light")
	assert.deepEqual({ ...iframe.messages.at(-1) }, { theme: "light" })
})

test("the load-event fallback adopts an automatic instance even if ready was not delivered", (t) => {
	const browser = new FakeWindow()
	const doc = new FakeDocument()
	const node = container("a")
	navigate(doc, node)
	t.after(installRemark42(browser, doc))
	doc.dispatchEvent(new Event("nav"))
	const dispatch = t.mock.method(browser, "dispatchEvent", () => true)
	evaluateLoader(browser, doc)
	dispatch.mock.restore()
	doc.scripts[0].dispatchEvent(new Event("load"))
	assert.equal(doc.iframes.length, 1)
	navigate(doc, null)
	assert.equal(doc.iframes[0].isConnected, false)
})

test("failed downloads show an isolated error and permit another attempt on a later navigation", (t) => {
	t.mock.method(console, "error", () => {})
	const browser = new FakeWindow()
	const doc = new FakeDocument()
	t.after(installRemark42(browser, doc))
	const first = container("a")
	navigate(doc, first)
	doc.scripts[0].dispatchEvent(new Event("error"))
	assert.match(first.textContent, /Comments could not be loaded/)
	assert.equal(doc.scripts[0].removed, true)
	navigate(doc, container("b"))
	assert.equal(doc.scripts.length, 2)
	evaluateLoader(browser, doc)
	assert.equal(iframeConfig(doc.iframes[0]).get("url"), "https://taras.life/comments/b")
})

test("a timeout reports failure but safely handles a module that executes afterward", (t) => {
	t.mock.method(console, "error", () => {})
	const browser = new FakeWindow()
	const doc = new FakeDocument()
	t.after(installRemark42(browser, doc))
	const node = container("a")
	navigate(doc, node)
	const timeout = [...browser.timers.values()].find((timer) => timer.delay === 20_000)
	assert.ok(timeout)
	timeout.callback()
	assert.match(node.textContent, /Comments could not be loaded/)
	assert.equal(doc.scripts[0].isConnected, true)
	navigate(doc, null)
	evaluateLoader(browser, doc)
	assert.equal(doc.getElementById("remark42"), null)
	assert.equal(doc.iframes[0].isConnected, false)
	assert.equal(doc.title, "Test page")
})

test("disposal during download discards a late automatic widget instead of orphaning it", () => {
	const browser = new FakeWindow()
	const doc = new FakeDocument()
	const dispose = installRemark42(browser, doc)
	navigate(doc, container("a"))
	const node = doc.getElementById("remark42")
	dispose()
	evaluateLoader(browser, doc)
	assert.equal(node.childNodes.length, 0)
	assert.equal(doc.iframes[0].isConnected, false)
	assert.equal(browser.timers.size, 1) // Only the upstream iframe's own reveal timer remains.
})

test("a module that loads during parsing can finish its automatic mount at DOMContentLoaded", (t) => {
	const browser = new FakeWindow()
	const doc = new FakeDocument()
	doc.readyState = "loading"
	t.after(installRemark42(browser, doc))
	navigate(doc, container("a"))
	evaluateLoader(browser, doc)
	doc.scripts[0].dispatchEvent(new Event("load"))
	assert.equal(doc.iframes.length, 0)
	doc.readyState = "interactive"
	doc.dispatchEvent(new Event("DOMContentLoaded"))
	assert.equal(doc.iframes.length, 1)
	navigate(doc, null)
	assert.equal(doc.iframes[0].isConnected, false)
})
